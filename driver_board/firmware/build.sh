#!/bin/bash
# Build the driver board's firmware with every version pinned.
#
#     driver_board/firmware/build.sh            # needs arduino-cli on PATH
#
# Waveshare's 0.96 image on the board was built with the Arduino ESP32 core 3.0.4
# (ESP-IDF 5.1.4, read from the image's app description) in September 2024, when
# the SparkFun ICM-20948 library was at 1.2.13; the others are the versions
# current then. The flash settings are the vendor image's own (DIO, 80 MHz, 4 MB
# layout, default partitions), so only the app slot is replaced when flashing.
# Output: build/ROS_Driver.ino.bin and its sha256.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SKETCH="$HERE/ROS_Driver"
BUILD="$HERE/build"
FQBN="esp32:esp32:esp32:FlashMode=dio,FlashFreq=80,FlashSize=4M,PartitionScheme=default"
CORE="esp32:esp32@3.0.4"
LIBS=(
  "ArduinoJson@7.1.0"
  "Adafruit SSD1306@2.5.10"
  "Adafruit GFX Library@1.11.10"
  "Adafruit BusIO@1.16.1"
  "INA219_WE@1.3.8"
  "ESP32Encoder@0.11.6"
  "PID_v2@0.1.1"
  "SimpleKalmanFilter@0.1.0"
  "SparkFun 9DoF IMU Breakout - ICM 20948 - Arduino Library@1.2.13"
)

KEY="$REPO/secrets/board-ota.key"
[ -s "$KEY" ] || { echo "no $KEY: the Wi-Fi update password" >&2; exit 1; }
printf '// Generated by build.sh from secrets/board-ota.key; never committed.\n#define OTA_PASSWORD "%s"\n' \
  "$(tr -d '\r\n' < "$KEY")" > "$SKETCH/ota_secret.h"

arduino-cli core update-index --additional-urls \
  https://espressif.github.io/arduino-esp32/package_esp32_index.json
arduino-cli core install "$CORE" --additional-urls \
  https://espressif.github.io/arduino-esp32/package_esp32_index.json
for lib in "${LIBS[@]}"; do arduino-cli lib install "$lib"; done
# Waveshare bundles the servo library with the firmware.
arduino-cli config set library.enable_unsafe_install true >/dev/null
arduino-cli lib install --zip-path <(cd "$HERE" && zip -qr - SCServo) 2>/dev/null \
  || cp -r "$HERE/SCServo" "$(arduino-cli config get directories.user)/libraries/"

# The DMP code in the IMU library is compiled only with ICM_20948_USE_DMP.
arduino-cli compile --fqbn "$FQBN" --output-dir "$BUILD" \
  --build-property "build.extra_flags=-DESP32 -DICM_20948_USE_DMP" \
  --warnings default "$SKETCH"
ls -l "$BUILD/ROS_Driver.ino.bin"
sha256sum "$BUILD/ROS_Driver.ino.bin"
# The app slot is 0x140000 bytes (default partitions).
size=$(stat -c %s "$BUILD/ROS_Driver.ino.bin")
[ "$size" -le $((0x140000)) ] || { echo "image $size bytes does not fit the 1310720-byte app slot" >&2; exit 1; }
